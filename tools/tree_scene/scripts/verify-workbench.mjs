import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
// 从项目根目录运行，固定手机视口验证真实输入、拖放与编辑返回。
const output = 'build/qa/workbench';
mkdirSync(output, {recursive:true});
const errors = [];
const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
const page = await browser.newPage({viewport:{width:430,height:932},recordVideo:{dir:output + '/video',size:{width:430,height:932}}});
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:8788');
await page.waitForTimeout(5000);
await page.mouse.click(215,120);
await page.waitForTimeout(400);
await page.mouse.click(210,485);
await page.keyboard.insertText('工作台验收');
await page.mouse.click(290,553);
await page.waitForTimeout(2500);
await page.mouse.click(215,460);
await page.waitForTimeout(1500);
await page.mouse.dblclick(107,512,{delay:60});
await page.waitForTimeout(1500);
await page.mouse.dblclick(322,512,{delay:60});
await page.waitForTimeout(1500);
await page.mouse.click(378,880);
await page.waitForTimeout(800);
await page.screenshot({path:output + '/capture-sheet.png'});
await page.locator('textarea').fill('工作台真实浏览器验收正文');
await page.mouse.click(215,887);
await page.waitForTimeout(900);
await page.mouse.click(350,30);
await page.waitForTimeout(1200);
await page.screenshot({path:output + '/carpet.png'});
await page.mouse.move(215,245);
await page.mouse.down();
await page.waitForTimeout(750);
await page.mouse.move(380,480,{steps:20});
await page.waitForTimeout(300);
await page.mouse.up();
await page.waitForTimeout(1400);
await page.mouse.click(380,480);
await page.waitForTimeout(1200);
await page.screenshot({path:output + '/section.png'});
await page.mouse.click(210,450);
await page.waitForTimeout(100);
await page.screenshot({path:output + '/editor-transition.png'});
await page.waitForTimeout(800);
await page.screenshot({path:output + '/editor.png'});
await page.mouse.click(130,100);
await page.keyboard.press('Control+A');
await page.keyboard.insertText('真实浏览器返回保存后的正文');
await page.mouse.click(28,26);
await page.waitForTimeout(1000);
await page.screenshot({path:output + '/returned.png'});
await page.mouse.click(210,450);
await page.waitForTimeout(700);
assert.equal(await page.getByPlaceholder('在这里尽情写，没有字数上限…').inputValue(), '真实浏览器返回保存后的正文');
await page.mouse.click(247,26);
await page.waitForTimeout(700);
await page.screenshot({path:output + '/return-dialog.png'});
await browser.close();
console.log('验收录屏',await page.video().path());

if (errors.length) throw new Error(errors.join('\n'));

